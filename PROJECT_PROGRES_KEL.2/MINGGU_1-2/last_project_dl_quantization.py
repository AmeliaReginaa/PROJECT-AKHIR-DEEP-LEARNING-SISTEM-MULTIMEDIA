    use_half = (name == 'float16')
    try:
        lat = measure_latency(item['model'], variant_device=item['device'],
                              use_half=use_half)
    except Exception as e:
        print(f'{name} error saat latency test: {e}')
        lat = None
    latency_results[name] = lat
    print(f'{name:<22} latency: {lat:.4f} ms' if lat else f'{name} latency: None')

