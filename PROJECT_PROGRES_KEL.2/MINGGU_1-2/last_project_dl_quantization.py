# G.2 LATENCY / KECEPATAN INFERENSI
@torch.no_grad()
def measure_latency(model, variant_device='cuda', use_half=False,
                    n_warmup=20, n_runs=100):
    model.eval()
    model  = model.to(variant_device)
    dummy  = torch.randn(1, 1, 48, 48).to(variant_device)
    if use_half:
        dummy = dummy.half()
    # Warmup
    for _ in range(n_warmup):
        _ = model(dummy)
    if variant_device == 'cuda':
        torch.cuda.synchronize()
    # Timing
    start = time.perf_counter()
    for _ in range(n_runs):
        _ = model(dummy)
    if variant_device == 'cuda':
        torch.cuda.synchronize()
    end = time.perf_counter()
    return ((end - start) / n_runs) * 1000   # ms

latency_results = {}
