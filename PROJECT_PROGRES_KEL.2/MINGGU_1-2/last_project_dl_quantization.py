def train_model(model, epochs=80, patience=10, target_acc=0.90,
                save_path='best_emotion_model.pth'):
    best_acc   = 0
    best_state = copy.deepcopy(model.state_dict())
    wait       = 0
    history    = []

    for epoch in range(1, epochs + 1):
        train_loss, train_acc = train_one_epoch(model, train_loader)
        val_loss,   val_acc   = evaluate(model, val_loader)
        scheduler.step(val_acc)

        history.append({
            'epoch': epoch,
            'train_loss': train_loss,
            'train_acc': train_acc,
            'val_loss': val_loss,
            'val_acc': val_acc,
            'lr': optimizer.param_groups[0]['lr']
        })

        print(f"Epoch {epoch:03d} | Train Acc: {train_acc:.4f} | "
              f"Val Acc: {val_acc:.4f} | Val Loss: {val_loss:.4f}")

        if val_acc > best_acc:
            best_acc   = val_acc
            best_state = copy.deepcopy(model.state_dict())
            torch.save(best_state, save_path)
            wait = 0
        else:
            wait += 1

        if val_acc >= target_acc:
            print(f'Early stopping: val acc sudah mencapai {target_acc*100:.0f}%')
            break
        if wait >= patience:
            print('Early stopping: tidak ada improvement lagi.')
            break

    model.load_state_dict(best_state)
    return model, pd.DataFrame(history), best_acc

