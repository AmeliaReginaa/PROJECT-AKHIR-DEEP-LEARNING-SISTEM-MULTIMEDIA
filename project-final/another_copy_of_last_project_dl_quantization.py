@torch.no_grad()
def evaluate_variant(model, loader, variant_device='cpu', use_half=False):
    model.eval()
    model = model.to(variant_device)
    correct, total = 0, 0
    for images, labels in loader:
        images = images.to(variant_device)
        labels = labels.to(variant_device)
        if use_half:
            images = images.half()
        outputs = model(images)
        _, preds = outputs.max(1)
        correct += preds.eq(labels).sum().item()
        total   += labels.size(0)
    return correct / total

